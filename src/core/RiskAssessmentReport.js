function classifyScore(score) {
  if (score >= 4) return 'CRITICAL';
  if (score === 3) return 'HIGH';
  if (score === 2) return 'MEDIUM';
  return 'LOW';
}

export function evaluateLiveRiskMatrix(planModel = {}) {
  const env = planModel.environment || {};
  const crane = planModel.crane || {};
  const cargo = planModel.cargo || {};
  const rigging = planModel.rigging || {};

  const groundKpa = Number.isFinite(Number(planModel.groundBearingKpa))
    ? Number(planModel.groundBearingKpa)
    : Number(env.actualGroundPressureKpa ?? Math.max(85, ((cargo.grossWeightKg || 16000) / 1000) * 8.2));
  const groundLimitKpa = Number(env.soilBearingCapacityKpa || 250);
  const groundRatio = groundKpa / Math.max(1, groundLimitKpa);
  const groundScore = groundRatio >= 1.0 ? 4 : (groundRatio >= 0.85 ? 3 : (groundRatio >= 0.65 ? 2 : 1));

  const upperAngles = Array.isArray(rigging.upperCables) ? rigging.upperCables.map((c) => Number(c.angleDeg)).filter(Number.isFinite) : [];
  const lowerAngles = Array.isArray(rigging.lowerCables) ? rigging.lowerCables.map((c) => Number(c.angleDeg)).filter(Number.isFinite) : [];
  const allAngles = [...upperAngles, ...lowerAngles];
  const minSlingAngle = allAngles.length ? Math.min(...allAngles) : Number(planModel.workingSlingAngleDeg || 60);
  const angleScore = minSlingAngle < 30 ? 4 : (minSlingAngle < 45 ? 3 : (minSlingAngle < 55 ? 2 : 1));

  const cogOffset = cargo.cogOffset || { x: 0, y: 0, z: 0 };
  const cogEccM = Number.isFinite(Number(planModel.cogOffsetM))
    ? Number(planModel.cogOffsetM)
    : Math.hypot(Number(cogOffset.x || 0), Number(cogOffset.z || 0));
  const cogScore = cogEccM >= 0.6 ? 4 : (cogEccM >= 0.35 ? 3 : (cogEccM >= 0.15 ? 2 : 1));

  const windMps = Number.isFinite(Number(planModel.windSpeedMps))
    ? Number(planModel.windSpeedMps)
    : Number(env.windSpeedMps ?? 3.5);
  const windLimitMps = Number(env.windLimitMps || 13.8);
  const windRatio = windMps / Math.max(1, windLimitMps);
  const windScore = windRatio >= 1.0 ? 4 : (windRatio >= 0.8 ? 3 : (windRatio >= 0.55 ? 2 : 1));

  const rawInspection = String(planModel.inspectionStatus || env.inspectionStatus || 'VALID').toUpperCase();
  const inspectionScore = (rawInspection === 'EXPIRED' || rawInspection === 'FAILED')
    ? 4
    : (rawInspection === 'EXPIRING_SOON' || rawInspection === 'UNVERIFIED' ? 2 : 1);

  const items = [
    {
      id: 'ground_bearing',
      factor: 'Ground Bearing Pressure / Outrigger Support',
      parameterValue: `${groundKpa.toFixed(1)} kPa (Limit: ${groundLimitKpa.toFixed(0)} kPa)`,
      probability: groundScore >= 3 ? 'HIGH' : (groundScore === 2 ? 'MEDIUM' : 'LOW'),
      severity: groundScore >= 3 ? 'CATASTROPHIC' : 'MAJOR',
      riskLevel: classifyScore(groundScore),
      mitigation: groundScore >= 3
        ? 'STOP: Deploy oversized timber/steel crane mats & compact subgrade soil before outrigger jacking.'
        : 'Verify timber crane mats centered beneath all outrigger floats (100% extension).'
    },
    {
      id: 'sling_angle',
      factor: 'Sling Angle Hazard & Load Amplification (LAF)',
      parameterValue: `Min alpha = ${minSlingAngle.toFixed(1)} deg (Target >= 45 deg)`,
      probability: angleScore >= 3 ? 'HIGH' : (angleScore === 2 ? 'MEDIUM' : 'LOW'),
      severity: angleScore >= 3 ? 'CRITICAL' : 'MAJOR',
      riskLevel: classifyScore(angleScore),
      mitigation: angleScore >= 3
        ? 'HAZARD (<45 deg): Increase upper bridle sling length or switch to spreader beam immediately.'
        : 'Confirm matched sling leg lengths and inspect bow shackles before lift-off.'
    },
    {
      id: 'cog_eccentricity',
      factor: 'CoG Eccentricity & Tilt Envelope',
      parameterValue: `Lateral offset = ${cogEccM.toFixed(2)} m (Crane cap: ${crane.ratedCapacityT || 75}T)`,
      probability: cogScore >= 3 ? 'HIGH' : (cogScore === 2 ? 'MEDIUM' : 'LOW'),
      severity: cogScore >= 3 ? 'MAJOR' : 'MODERATE',
      riskLevel: classifyScore(cogScore),
      mitigation: cogScore >= 3
        ? 'Perform 150 mm trial lift check; re-adjust turnbuckles or offset master link to center CoG under hook.'
        : 'Monitor cargo plumbness during initial trial lift (100-150 mm clearance).'
    },
    {
      id: 'wind_factor',
      factor: 'Wind Velocity & Pendulum Sail Area',
      parameterValue: `${windMps.toFixed(1)} m/s (Max operational limit: ${windLimitMps.toFixed(1)} m/s)`,
      probability: windScore >= 3 ? 'HIGH' : (windScore === 2 ? 'MEDIUM' : 'LOW'),
      severity: windScore >= 3 ? 'CRITICAL' : 'MODERATE',
      riskLevel: classifyScore(windScore),
      mitigation: windScore >= 3
        ? 'SUSPEND LIFT: Wind approaches/exceeds crane chart threshold. Lower load and deploy dual taglines.'
        : 'Attach dual insulated taglines (min 2 riggers) & continuously monitor boom-tip anemometer.'
    },
    {
      id: 'inspection_status',
      factor: 'Rigging Gear & Crane NDT/LOLER Inspection Status',
      parameterValue: `Certification: ${rawInspection}`,
      probability: inspectionScore >= 3 ? 'HIGH' : (inspectionScore === 2 ? 'MEDIUM' : 'LOW'),
      severity: inspectionScore >= 3 ? 'CRITICAL' : 'MODERATE',
      riskLevel: classifyScore(inspectionScore),
      mitigation: inspectionScore >= 3
        ? 'LOCKOUT: Valid annual NDT/MPI certificate & color-code tag required before hook attachment.'
        : 'Pre-use visual inspection of wire ropes, hook safety latch, and shackle pins verified.'
    }
  ];

  const maxScore = Math.max(groundScore, angleScore, cogScore, windScore, inspectionScore);
  return {
    overallRisk: classifyScore(maxScore),
    evaluatedAt: new Date().toISOString(),
    items
  };
}

