export function renderRiskAssessmentSectionHTML(planModel = {}, branding = {}) {
  const matrix = evaluateLiveRiskMatrix(planModel);
  const badgeColor = matrix.overallRisk === 'CRITICAL'
    ? '#dc2626'
    : (matrix.overallRisk === 'HIGH' ? '#ea580c' : (matrix.overallRisk === 'MEDIUM' ? '#d97706' : '#059669'));

  const rows = matrix.items.map((item) => {
    const color = item.riskLevel === 'CRITICAL'
      ? '#dc2626'
      : (item.riskLevel === 'HIGH' ? '#ea580c' : (item.riskLevel === 'MEDIUM' ? '#b45309' : '#047857'));
    return `<tr>
      <td style="padding:7px 9px;border:1px solid #cbd5e1;font-weight:700;">${item.factor}</td>
      <td style="padding:7px 9px;border:1px solid #cbd5e1;font-family:monospace;">${item.parameterValue}</td>
      <td style="padding:7px 9px;border:1px solid #cbd5e1;font-weight:800;color:${color};text-align:center;">${item.riskLevel}</td>
      <td style="padding:7px 9px;border:1px solid #cbd5e1;">${item.mitigation}</td>
    </tr>`;
  }).join('');

  return `<div class="box-card pdf-page-break" id="jsa-hse-risk-page">
    ${branding.headerStripHtml || ''}
    <div style="display:flex;justify-content:space-between;align-items:center;margin-bottom:10px;">
      <h3 style="margin:0;">INTEGRATED JSA / HSE RISK ASSESSMENT MATRIX (DYNAMIC 3D PHYSICS)</h3>
      <span style="background:${badgeColor};color:#fff;padding:4px 10px;border-radius:4px;font-weight:800;font-size:11px;">OVERALL RISK: ${matrix.overallRisk}</span>
    </div>
    <table style="width:100%;border-collapse:collapse;font-size:11px;">
      <thead>
        <tr style="background:#f1f5f9;">
          <th style="padding:7px 9px;border:1px solid #cbd5e1;text-align:left;width:23%;">Hazard Category</th>
          <th style="padding:7px 9px;border:1px solid #cbd5e1;text-align:left;width:24%;">Live 3D Telemetry</th>
          <th style="padding:7px 9px;border:1px solid #cbd5e1;text-align:center;width:11%;">Rating</th>
          <th style="padding:7px 9px;border:1px solid #cbd5e1;text-align:left;">Engineered Mitigation &amp; Control</th>
        </tr>
      </thead>
      <tbody>${rows}</tbody>
    </table>
    ${branding.footerHtml || ''}
  </div>`;
}
