import { describe, it, expect } from 'vitest';
import * as THREE from 'three';
import { AssetPipeline } from '../src/core/AssetPipeline.js';
import { HullOptimizer } from '../src/core/HullOptimizer.js';
import { ASSET_SPECS } from '../src/core/AssetSpecs.js';

describe('AssetPipeline & Metric Scale Normalizer (CAE Standard)', () => {
    it('1. Auto-detects millimeter (mm) CAD units and normalizes container to 1:1 real-world meters', () => {
        // Create container 20ft geometry modeled in millimeters (typical SolidWorks / STEP / GrabCAD export)
        const rawGroup = new THREE.Group();
        const boxMesh = new THREE.Mesh(
            new THREE.BoxGeometry(6058, 2591, 2438), // mm
            new THREE.MeshStandardMaterial()
        );
        rawGroup.add(boxMesh);

        const { root, report } = AssetPipeline.normalizeAsset(rawGroup, {
            specKey: 'container_20ft',
            mode: 'cad_strict'
        });

        expect(report.detectedUnit).toBe('mm');
        expect(report.appliedScaleFactor).toBeCloseTo(0.001, 5);
        expect(report.status).toBe('PASS');
        expect(report.dimensionsNormalized.x).toBeCloseTo(6.058, 2);
        expect(report.dimensionsNormalized.y).toBeCloseTo(2.591, 2);
        expect(report.dimensionsNormalized.z).toBeCloseTo(2.438, 2);

        // Check bounding box of normalized root group
        const bbox = new THREE.Box3().setFromObject(root);
        const size = new THREE.Vector3();
        bbox.getSize(size);
        expect(size.x).toBeCloseTo(6.058, 2);
        expect(size.y).toBeCloseTo(2.591, 2);
        expect(size.z).toBeCloseTo(2.438, 2);

        // Center pivot
        const center = new THREE.Vector3();
        bbox.getCenter(center);
        expect(Math.abs(center.x)).toBeLessThan(0.01);
        expect(Math.abs(center.y)).toBeLessThan(0.01);
        expect(Math.abs(center.z)).toBeLessThan(0.01);
    });

    it('2. Auto-detects Z-up orientation and rotates model to Y-up', () => {
        // In 3ds Max / Blender / CAD, Z is often UP:
        // Length = X (6058), Height = Z (2591), Width = Y (2438)
        const rawGroup = new THREE.Group();
        const boxMesh = new THREE.Mesh(
            new THREE.BoxGeometry(6058, 2438, 2591),
            new THREE.MeshStandardMaterial()
        );
        rawGroup.add(boxMesh);

        const { root, report } = AssetPipeline.normalizeAsset(rawGroup, {
            specKey: 'container_20ft',
            mode: 'cad_strict'
        });

        expect(report.detectedUnit).toBe('mm');
        expect(report.detectedUpAxis).toBe('Z');
        expect(report.status).toBe('PASS');

        const bbox = new THREE.Box3().setFromObject(root);
        const size = new THREE.Vector3();
        bbox.getSize(size);
        // Height along Y must be 2.591m
        expect(size.y).toBeCloseTo(2.591, 2);
        expect(size.x).toBeCloseTo(6.058, 2);
    });

    it('3. AI Mesh mode (ai_fit) applies uniform scaling without non-uniform stretching', () => {
        // AI model generated by Meshy / Tripo / 3D generator (normalized to arbitrary ~1.5 units)
        const rawGroup = new THREE.Group();
        const boxMesh = new THREE.Mesh(
            new THREE.BoxGeometry(3.0, 1.3, 1.2),
            new THREE.MeshStandardMaterial()
        );
        rawGroup.add(boxMesh);

        const { root, report } = AssetPipeline.normalizeAsset(rawGroup, {
            specKey: 'container_20ft',
            mode: 'ai_fit'
        });

        // Must scale by a uniform scalar
        expect(root.children[0].scale.x).toBe(root.children[0].scale.y);
        expect(root.children[0].scale.y).toBe(root.children[0].scale.z);
        expect(report.warnings.some(w => w.includes('AI_FIT'))).toBe(true);
    });

    it('4. Rejects grossly mismatched geometry (1m cube labelled as 20ft container)', () => {
        const rawGroup = new THREE.Group();
        rawGroup.add(new THREE.Mesh(new THREE.BoxGeometry(1.0, 1.0, 1.0), new THREE.MeshStandardMaterial()));

        const { report } = AssetPipeline.normalizeAsset(rawGroup, {
            specKey: 'container_20ft',
            mode: 'cad_strict'
        });

        // Deviation of 1m cube vs 6m container exceeds tolerance
        expect(report.status).toBe('FAIL');
        expect(report.warnings.some(w => w.includes('vượt quá'))).toBe(true);
    });

    it('5. Extracts model ANCHOR_* nodes if present, otherwise synthesizes ISO 1161 pad-eyes', () => {
        // Case A: Model with explicit ANCHOR_ nodes
        const modelWithAnchors = new THREE.Group();
        modelWithAnchors.add(new THREE.Mesh(new THREE.BoxGeometry(6.058, 2.591, 2.438), new THREE.MeshStandardMaterial()));
        const anchorNode = new THREE.Object3D();
        anchorNode.name = 'ANCHOR_PADEYE_0';
        anchorNode.position.set(2.935, 1.245, 1.129);
        modelWithAnchors.add(anchorNode);

        const resA = AssetPipeline.normalizeAsset(modelWithAnchors, { specKey: 'container_20ft' });
        expect(resA.report.anchorsCount).toBe(1);
        expect(resA.report.anchors[0].id).toBe('ANCHOR_PADEYE_0');
        expect(resA.report.anchors[0].source).toBe('model_empty_node');

        // Case B: Model without anchors -> synthesizes 4 standard corner castings
        const modelWithoutAnchors = new THREE.Group();
        modelWithoutAnchors.add(new THREE.Mesh(new THREE.BoxGeometry(6.058, 2.591, 2.438), new THREE.MeshStandardMaterial()));
        const resB = AssetPipeline.normalizeAsset(modelWithoutAnchors, { specKey: 'container_20ft' });
        expect(resB.report.anchorsCount).toBe(4);
        expect(resB.report.anchors[0].source).toBe('synthesized_standard');
    });

    it('6. Bottom pivot for cranes positions base exactly flush at quay level (min.y = 0)', () => {
        const craneGroup = new THREE.Group();
        craneGroup.add(new THREE.Mesh(new THREE.BoxGeometry(28.0, 56.0, 88.0), new THREE.MeshStandardMaterial()));

        const { root, report } = AssetPipeline.normalizeAsset(craneGroup, {
            specKey: 'sts_gantry_crane'
        });

        const bbox = new THREE.Box3().setFromObject(root);
        // Base of crane must be flush with ground (min.y = 0)
        expect(Math.abs(bbox.min.y)).toBeLessThan(0.01);
        // Center along X and Z must be 0
        const center = new THREE.Vector3();
        bbox.getCenter(center);
        expect(Math.abs(center.x)).toBeLessThan(0.01);
        expect(Math.abs(center.z)).toBeLessThan(0.01);
    });

    it('7. AssetLoaders parses real container_20ft.glb with PASS compliance and 5 extracted anchors', async () => {
        const fs = await import('fs');
        const { AssetLoaders } = await import('../src/core/AssetLoaders.js');
        const buf = fs.readFileSync('public/assets/models/container_20ft.glb').buffer;

        const loaders = new AssetLoaders();
        const { root, report } = await loaders.parseData(buf, 'glb', { specKey: 'container_20ft' });

        expect(report.status).toBe('PASS');
        expect(report.detectedUnit).toBe('m');
        expect(report.dimensionsNormalized.x).toBeCloseTo(6.058, 0);
        expect(report.dimensionsNormalized.y).toBeCloseTo(2.591, 0);
        expect(report.dimensionsNormalized.z).toBeCloseTo(2.438, 0);
        expect(report.anchorsCount).toBe(5);
        expect(root.userData.isNormalizedAsset).toBe(true);
    });

    it('8. AssetLoaders parses real sts_crane.glb with bottom pivot resting on quay at Y = 0', async () => {
        const fs = await import('fs');
        const { AssetLoaders } = await import('../src/core/AssetLoaders.js');
        const buf = fs.readFileSync('public/assets/models/sts_crane.glb').buffer;

        const loaders = new AssetLoaders();
        const { root, report } = await loaders.parseData(buf, 'glb', { specKey: 'sts_gantry_crane' });

        expect(report.status).toBe('PASS');
        const bbox = new THREE.Box3().setFromObject(root);
        expect(Math.abs(bbox.min.y)).toBeLessThan(0.05);
        expect(report.anchors.some(a => a.id === 'ANCHOR_TROLLEY')).toBe(true);
    });

    it('9. HullOptimizer culls interior sub-meshes completely hidden inside outer shell', () => {
        const root = new THREE.Group();
        // Outer hull casing (10m x 4m x 4m)
        const outerMesh = new THREE.Mesh(new THREE.BoxGeometry(10, 4, 4), new THREE.MeshStandardMaterial());
        root.add(outerMesh);

        // Internal engine block completely inside (2m x 1.5m x 1.5m at center 0,0,0)
        const interiorEngine = new THREE.Mesh(new THREE.BoxGeometry(2, 1.5, 1.5), new THREE.MeshStandardMaterial());
        interiorEngine.name = 'interior_engine_block';
        root.add(interiorEngine);

        expect(root.children.length).toBe(2);
        const { culledCount } = HullOptimizer.cullInteriorParts(root, { insetMargin: 0.1 });
        expect(culledCount).toBe(1);
        expect(root.children.length).toBe(1);
        expect(root.children[0]).toBe(outerMesh);
    });

    it('10. HullOptimizer decimates dense geometry while preserving outer bounding box', () => {
        // High density sphere (128x128 = 32,512 tris)
        const denseSphere = new THREE.Mesh(new THREE.SphereGeometry(3, 128, 128), new THREE.MeshStandardMaterial());
        const initialTris = HullOptimizer.getTriCount(denseSphere);
        expect(initialTris).toBeGreaterThan(30000);

        const { stats } = HullOptimizer.optimizeHierarchy(denseSphere, { maxTris: 5000 });
        expect(stats.finalTris).toBeLessThan(6000);
        expect(stats.reductionPct).toBeGreaterThan(75);

        // Verify bounding size is maintained (~6m diameter)
        const bbox = new THREE.Box3().setFromObject(denseSphere);
        const size = new THREE.Vector3();
        bbox.getSize(size);
        expect(size.x).toBeCloseTo(6, 1);
        expect(size.y).toBeCloseTo(6, 1);
        expect(size.z).toBeCloseTo(6, 1);
    });

    it('11. AssetPipeline normalizes 3D asset with user-specified target dimensions (L, W, H)', () => {
        const rawGroup = new THREE.Group();
        rawGroup.add(new THREE.Mesh(new THREE.BoxGeometry(1, 1, 1), new THREE.MeshStandardMaterial()));

        const { root, report } = AssetPipeline.normalizeAsset(rawGroup, {
            specKey: 'generic_cargo',
            targetDimensions: { x: 14.5, y: 3.8, z: 4.2 },
            forceExactDimensions: true
        });

        const bbox = new THREE.Box3().setFromObject(root);
        const sz = new THREE.Vector3();
        bbox.getSize(sz);
        expect(sz.x).toBeCloseTo(14.5, 1);
        expect(sz.y).toBeCloseTo(3.8, 1);
        expect(sz.z).toBeCloseTo(4.2, 1);
        expect(report.dimensionsNormalized.x).toBeCloseTo(14.5, 1);
    });
});
